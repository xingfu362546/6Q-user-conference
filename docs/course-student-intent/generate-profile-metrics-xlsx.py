def copy_cell_style(src, dst):
    if src.has_style:
        dst.font = copy(src.font)
        dst.fill = copy(src.fill)
        dst.border = copy(src.border)
        dst.alignment = copy(src.alignment)
        dst.number_format = src.number_format


def write_sheet(wb):
    if SHEET_NAME in wb.sheetnames:
        del wb[SHEET_NAME]
    ws = wb.create_sheet(SHEET_NAME)

    header_fill = PatternFill("solid", fgColor="9A38D7")
    src_fill = PatternFill("solid", fgColor="A38200")
    white = Font(name="宋体", size=10, bold=True, color="FFFFFF")
    body_font = Font(name="宋体", size=10)
    thin = Border(
        left=Side(style="thin", color="B4B4B4"),
        right=Side(style="thin", color="B4B4B4"),
        top=Side(style="thin", color="B4B4B4"),
        bottom=Side(style="thin", color="B4B4B4"),
    )
    title_align = Alignment(wrap_text=True, vertical="center", horizontal="left")
    cell_align = Alignment(wrap_text=True, vertical="center")

    ws.merge_cells("A1:E1")
    ws["A1"] = TITLE
    ws["A1"].font = white
    ws["A1"].fill = header_fill
    ws["A1"].alignment = title_align
    for col in range(1, 6):
        ws.cell(1, col).fill = header_fill
        ws.cell(1, col).border = thin

    for col, name in enumerate(HEADERS, 1):
        cell = ws.cell(2, col, name)
        cell.font = white
        cell.fill = src_fill if col == 5 else header_fill
        cell.alignment = Alignment(wrap_text=True, vertical="center")
        cell.border = thin

    for i, row in enumerate(ROWS, 3):
        for col, val in enumerate(row, 1):
            cell = ws.cell(i, col, val)
            cell.font = body_font
            cell.alignment = cell_align
            cell.border = thin
        ws.row_dimensions[i].height = 48

    # Merge consecutive 指标板块 cells (column A)
    start = 3
    while start <= 2 + len(ROWS):
        name = ws.cell(start, 1).value
        end = start
        while end + 1 <= 2 + len(ROWS) and ws.cell(end + 1, 1).value == name:
            end += 1
        if end > start:
            ws.merge_cells(start_row=start, start_column=1, end_row=end, end_column=1)
            ws.cell(start, 1).alignment = cell_align
        start = end + 1

    ws.row_dimensions[1].height = 46.5
    ws.row_dimensions[2].height = 28
    ws.column_dimensions["A"].width = 28
    ws.column_dimensions["B"].width = 32
    ws.column_dimensions["C"].width = 62
    ws.column_dimensions["D"].width = 36
    ws.column_dimensions["E"].width = 52
    ws.freeze_panes = "A3"
    ws.auto_filter.ref = f"A2:E{2 + len(ROWS)}"
    ws.sheet_view.showGridLines = False
    return ws


def main():
    if not DESKTOP.exists():
        raise SystemExit(f"missing template: {DESKTOP}")
    wb = load_workbook(DESKTOP)
    write_sheet(wb)
    DESKTOP.parent.mkdir(parents=True, exist_ok=True)
    wb.save(DESKTOP)
    REPO_OUT.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(DESKTOP, REPO_OUT)
    print(f"sheets={wb.sheetnames}")
    print(f"archive_rows={len(ROWS)}")
    print(f"desktop={DESKTOP}")
    print(f"repo={REPO_OUT}")


if __name__ == "__main__":
    main()
